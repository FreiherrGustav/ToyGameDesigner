const fs=require('fs');const { chromium } = require('/opt/node22/lib/node_modules/playwright');
(async () => {
  const b = await chromium.launch({ executablePath: '/opt/pw-browsers/chromium' });
  const p = await b.newPage({ viewport: { width: 1366, height: 768 } });
  p.on('dialog', d => d.accept()); const errs = []; p.on('pageerror', e => errs.push(e.message));
  await p.goto('file://'+process.cwd()+'/index.html#t');
  let f=0;const ok=(c,m)=>{console.log(c?'ok  ':'FAIL',m);if(!c)f++;};
  const tabs=()=>p.$$eval('#roomTabRow .roomTab > .tbtn:first-child',l=>l.map(x=>x.textContent));
  await p.click('#roomTabRow .tbtn.ghost');
  ok((await tabs()).length===2,'two rooms '+await tabs());
  await p.dblclick('#roomTabRow .roomTab.current > .tbtn:first-child');
  ok(await p.isVisible('.roomNameInput'),'double click opens the name box');
  await p.fill('.roomNameInput','Lava Cave');
  await p.press('.roomNameInput','Enter');
  ok((await tabs()).some(t=>t.startsWith('Lava Cave')),'renamed: '+await tabs());
  ok(!(await p.isVisible('.roomNameInput')),'box closed');
  await p.dblclick('#roomTabRow .roomTab.current > .tbtn:first-child');
  await p.fill('.roomNameInput','Nope');
  await p.press('.roomNameInput','Escape');
  ok((await tabs()).some(t=>t.startsWith('Lava Cave')),'Escape cancels');
  await p.dblclick('#roomTabRow .roomTab.current > .tbtn:first-child');
  await p.fill('.roomNameInput','');
  await p.press('.roomNameInput','Enter');
  ok((await tabs()).some(t=>t.startsWith('Lava Cave')),'empty keeps old');
  await p.dblclick('#roomTabRow .roomTab.current > .tbtn:first-child');
  await p.fill('.roomNameInput','Sky');
  await p.click('#modeObject');
  ok((await tabs()).some(t=>t.startsWith('Sky')),'clicking away keeps the name');
  await p.click('#undoBtn');
  ok((await tabs()).some(t=>t.startsWith('Lava Cave')),'undo restores the old name: '+await tabs());
  ok(errs.length===0,'no errors '+errs);
  await b.close();process.exit(f?1:0);
})();
